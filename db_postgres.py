"""Base de datos PostgreSQL opcional para Cripta Pixel Online.

Se activa solo cuando DATABASE_URL está definido. La lógica de combate permanece
independiente del almacenamiento. No registrar ni mostrar DATABASE_URL.
"""
from __future__ import annotations
import datetime as dt
import hashlib
import hmac
import re
import secrets


class PostgresDatabase:
    def __init__(self, url: str):
        if not isinstance(url, str) or not url.startswith(('postgresql://', 'postgres://')):
            raise ValueError('DATABASE_URL debe ser una URL postgresql:// de Neon.')
        try:
            import psycopg
        except ImportError as ex:
            raise RuntimeError('Falta psycopg: instala requirements-cloud.txt en el servidor.') from ex
        self._driver = psycopg
        self._url = url
        self._init()

    def connection(self):
        # Desactivar prepared statements ayuda a trabajar con el pooler de Neon.
        # El contexto confirma o revierte la transacción y cierra la conexión.
        return self._driver.connect(self._url, connect_timeout=12, prepare_threshold=None)

    def _init(self):
        with self.connection() as db:
            db.execute('''CREATE TABLE IF NOT EXISTS users (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                username TEXT NOT NULL,
                salt BYTEA NOT NULL,
                hash BYTEA NOT NULL,
                created_at TEXT NOT NULL)''')
            db.execute('CREATE UNIQUE INDEX IF NOT EXISTS users_lower_name_idx ON users (lower(username))')
            db.execute('''CREATE TABLE IF NOT EXISTS results (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id BIGINT NOT NULL REFERENCES users(id),
                mode TEXT NOT NULL,
                points INTEGER NOT NULL,
                wins INTEGER NOT NULL,
                kills INTEGER NOT NULL,
                floors INTEGER NOT NULL,
                day TEXT NOT NULL,
                played_at TEXT NOT NULL)''')
            db.execute('CREATE INDEX IF NOT EXISTS idx_results_day ON results(day, user_id)')
            db.execute('CREATE INDEX IF NOT EXISTS idx_results_mode_day ON results(mode, day, user_id)')

    def register(self, username: str, password: str):
        if not re.fullmatch(r'[A-Za-z0-9_]{3,18}', username):
            return None, 'Usuario: 3-18 letras, numeros o _.'
        if not isinstance(password, str) or not 6 <= len(password) <= 72:
            return None, 'Contrasena: entre 6 y 72 caracteres.'
        salt = secrets.token_bytes(16)
        pwd_hash = hashlib.pbkdf2_hmac('sha256', password.encode(), salt, 240_000)
        try:
            with self.connection() as db:
                row = db.execute(
                    'INSERT INTO users(username,salt,hash,created_at) VALUES (%s,%s,%s,%s) RETURNING id',
                    (username, salt, pwd_hash, dt.datetime.now(dt.timezone.utc).isoformat()),
                ).fetchone()
                return row[0], 'Cuenta creada correctamente.'
        except self._driver.errors.UniqueViolation:
            return None, 'Ese usuario ya existe.'

    def login(self, username: str, password: str):
        with self.connection() as db:
            row = db.execute(
                'SELECT id, username, salt, hash FROM users WHERE lower(username)=lower(%s)',
                (username,),
            ).fetchone()
        if row is None:
            return None, None, 'Credenciales invalidas.'
        check = hashlib.pbkdf2_hmac('sha256', str(password).encode(), row[2], 240_000)
        if not hmac.compare_digest(check, row[3]):
            return None, None, 'Credenciales invalidas.'
        return row[0], row[1], 'Bienvenido.'

    def result(self, user_id: int, mode: str, points: int, wins: int, kills: int, floors: int):
        from server import BOGOTA  # evita repetir reglas de zona horaria
        current = dt.datetime.now(BOGOTA)
        with self.connection() as db:
            db.execute('''INSERT INTO results(user_id,mode,points,wins,kills,floors,day,played_at)
                       VALUES (%s,%s,%s,%s,%s,%s,%s,%s)''',
                       (user_id, mode, int(points), int(wins), int(kills), int(floors),
                        current.date().isoformat(), current.isoformat()))

    def ranking(self, day: str | None = None, limit: int = 12, mode: str | None = None):
        from server import GAME_MODES, today
        if mode is not None and mode not in GAME_MODES:
            raise ValueError('Modo de clasificación no válido')
        day = day or today()
        params = (day, mode, int(limit)) if mode else (day, int(limit))
        mode_filter = ' AND r.mode=%s' if mode else ''
        with self.connection() as db:
            rows = db.execute('''SELECT u.username, SUM(r.points) AS total,
                 SUM(r.wins) AS victories, COUNT(*) AS games, MAX(r.points) AS best
                 FROM results r JOIN users u ON u.id = r.user_id
                 WHERE r.day=%s''' + mode_filter + ''' GROUP BY r.user_id, u.username
                 ORDER BY total DESC, victories DESC, best DESC, u.username ASC LIMIT %s''',
                 params).fetchall()
        return [{'name': n, 'points': int(p), 'wins': int(w), 'games': int(g), 'best': int(b)}
                for n, p, w, g, b in rows]
