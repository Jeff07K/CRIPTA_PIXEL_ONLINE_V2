class FakeConnection:
    def __init__(self,path):
        self.conn=sqlite3.connect(path)
    def __enter__(self): return self
    def __exit__(self,*args):
        try:
            if args[0]:self.conn.rollback()
            else:self.conn.commit()
        finally:self.conn.close()
    def execute(self, sql, params=None):
        sql=sql.replace('id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY',
                        'id INTEGER PRIMARY KEY AUTOINCREMENT').replace('BYTEA','BLOB')
        sql=sql.replace('BIGINT NOT NULL REFERENCES users(id)', 'INTEGER NOT NULL REFERENCES users(id)')
        sql=sql.replace('%s','?')
        return self.conn.execute(sql,params or ())


class PostgresBackendTests(unittest.TestCase):
    def test_user_registration_login_ranking_and_modes_in_psycopg_compatible_adapter(self):
        with tempfile.TemporaryDirectory() as tmp:
            db_path=str(Path(tmp)/'simulated_postgres.db')
            fake=types.ModuleType('psycopg')
            fake.connect=lambda *args,**kwargs:FakeConnection(db_path)
            fake.errors=types.SimpleNamespace(UniqueViolation=sqlite3.IntegrityError)
            with patch.dict(sys.modules,{'psycopg':fake}), patch.dict(os.environ,{'DATABASE_URL':'postgresql://example.invalid/mock'}):
                game=GameServer('127.0.0.1',0,str(Path(tmp)/'local.db'))
                db=game.db
                self.assertEqual(type(db).__name__,'PostgresDatabase')
                alice,msg=db.register('Caballero','contrasena123')
                self.assertIsInstance(alice,int)
                duplicate,msg=db.register('CABALLERO','contrasena123')
                self.assertIsNone(duplicate)
                self.assertEqual(msg,'Ese usuario ya existe.')
                ident,user,msg=db.login('caballero','contrasena123')
                self.assertEqual((ident,user),(alice,'Caballero'))
                self.assertIsNone(db.login('caballero','equivocada')[0])
                db.result(alice,'solo',200,1,4,3)
                db.result(alice,'coop',100,0,2,2)
                db.result(alice,'pvp',50,1,1,0)
                self.assertEqual(db.ranking(mode='solo')[0]['points'],200)
                self.assertEqual(db.ranking(mode='coop')[0]['points'],100)
                self.assertEqual(db.ranking(mode='pvp')[0]['points'],50)
                self.assertEqual(db.ranking(mode='solo')[0]['wins'],1)
                self.assertEqual(db.ranking(day='2000-01-01',mode='solo'),[])
                self.assertEqual(db.ranking(mode='solo')[0]['games'],1)
                other=game.db.__class__('postgresql://example.invalid/mock')
                self.assertEqual(other.login('caballero','contrasena123')[0],alice)
                self.assertEqual(other.ranking(day=today(),mode='solo')[0]['points'],200)
                self.assertFalse(Path(tmp,'local.db').exists())

